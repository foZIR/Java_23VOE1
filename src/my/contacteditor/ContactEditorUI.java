    private void jButtonResultActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonResultActionPerformed
    DefaultTableModel tModel = (DefaultTableModel) jTable1.getModel();
    int rowNum = jTable1.getSelectedRow();
    
    if (rowNum == -1) {
        JOptionPane.showMessageDialog(this,
            "Выберите строку!",
            "Предупреждение", JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    if (clients.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Нет подключённых клиентов!",
            "Ошибка", JOptionPane.ERROR_MESSAGE);
        return;
    }
    
    try {
        double lowerLimit = Double.parseDouble(tModel.getValueAt(rowNum, 0).toString());
        double upperLimit = Double.parseDouble(tModel.getValueAt(rowNum, 1).toString());
        double range = Double.parseDouble(tModel.getValueAt(rowNum, 2).toString());
        
        // Проверка диапазона
        new RecIntegral(lowerLimit, upperLimit, range);
        
        selectedRowForCalc = rowNum;
        jButtonResult.setEnabled(false);
        
        sendTasksToClients(lowerLimit, upperLimit, range);
        
    } catch (InvalidRangeException exe) {
        JOptionPane.showMessageDialog(this,
            exe.getMessage() + "Вы ввели: " + exe.getErrVal(),
            "Ошибка диапазона", JOptionPane.WARNING_MESSAGE);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,
            "Введите корректные числа",
            "Ошибка ввода", JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_jButtonResultActionPerformed

