    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        // TODO add your handling code here:
        JFileChooser fileChooser = new JFileChooser();
    fileChooser.setDialogTitle("Загрузить из текстового файла");
    FileNameExtensionFilter filter = new FileNameExtensionFilter("Текстовые файлы (*.txt)", "txt");
    fileChooser.setFileFilter(filter);
    
    int userSelection = fileChooser.showOpenDialog(this);
    
    if (userSelection == JFileChooser.APPROVE_OPTION) {
        File fileToOpen = fileChooser.getSelectedFile();
        
        try (BufferedReader reader = new BufferedReader(new FileReader(fileToOpen))) {
            arrInteg.clear();
            DefaultTableModel tModel = (DefaultTableModel) jTable1.getModel();
            tModel.setRowCount(0);
            
            String line;
            boolean isFirstLine = true;
            
            while ((line = reader.readLine()) != null) {
                if (isFirstLine) {
                    isFirstLine = false;
                    continue;
                }
                
                String[] parts = line.split(";");
                if (parts.length == 4) {
                    try {
                        double lowerLimit = Double.parseDouble(parts[0]);
                        double upperLimit = Double.parseDouble(parts[1]);
                        double range = Double.parseDouble(parts[2]);
                        double result = Double.parseDouble(parts[3]);
                        
                        RecIntegral rec = new RecIntegral(lowerLimit, upperLimit, range);
                        rec.setResult(result);
                        arrInteg.add(rec);
                        
                        tModel.addRow(new Object[] {rec.getLowerLimit(), 
                                                   rec.getUpperLimit(), 
                                                   rec.getRange(), 
                                                   rec.getResult()});
                    } catch (NumberFormatException | InvalidRangeException ex) {
                        System.err.println("Пропущена некорректная строка: " + line);
                    }
                }
            }
            
            JOptionPane.showMessageDialog(this,
                "Данные успешно загружены!\nЗагружено записей: " + arrInteg.size(),
                "Загрузка выполнена", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this,
                "Ошибка при загрузке файла:\n" + ex.getMessage(),
                "Ошибка загрузки", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_jButton5ActionPerformed

